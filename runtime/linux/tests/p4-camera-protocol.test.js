test('P4 camera physical enrollment accepts only an immediate single-face BOOT confirmation', () => {
  const main = fs.readFileSync(CAMERA_MAIN_PATH, 'utf8')
  const inference = fs.readFileSync(INFERENCE_PATH, 'utf8')
  assert.match(main, /CONFIG_APP_CAMERA_OWNER_CONFIRM_PIN/)
  assert.match(main, /GPIO_INTR_NEGEDGE/)
  assert.match(main, /s_owner_enrollment_pending = true/)
  assert.match(main, /if \(!s_owner_enrollment_pending \|\| !owner_confirmation_active\(\)\)/)
  assert.match(main, /metadata->faces_count != 1 \|\| metadata->current_face_index != 0/)
  assert.match(main, /Owner enrollment cancelled: exactly one face was not visible at confirmation/)
  assert.doesNotMatch(main, /ENROLL /)
  assert.doesNotMatch(main, /command_reader/)
  assert.match(inference, /enrollment_input\.size\(\) != 1/)
  assert.match(inference, /RECOGNITION_THRESHOLD = 0\.75F/)
})

test('P4 diagnostic snapshots require an explicitly enabled diagnostic build', () => {
  const main = fs.readFileSync(CAMERA_MAIN_PATH, 'utf8')
  const kconfig = fs.readFileSync(KCONFIG_PATH, 'utf8')
  const sdkconfig = fs.readFileSync(SDKCONFIG_DEFAULTS_PATH, 'utf8')
  assert.match(kconfig, /config APP_CAMERA_DIAGNOSTIC_SNAPSHOT/)
  assert.match(kconfig, /default n/)
  assert.match(main, /#if CONFIG_APP_CAMERA_DIAGNOSTIC_SNAPSHOT/)
  assert.match(main, /P4_SNAPSHOT_BEGIN/)
  assert.match(main, /P4_SNAPSHOT_DATA/)
  assert.match(main, /DIAGNOSTIC_SNAPSHOT_LINE_BYTES 16/)
  assert.match(main, /CONFIG_APP_CAMERA_DIAGNOSTIC_SNAPSHOT_DELAY_SECONDS/)
  assert.match(main, /#if !CONFIG_APP_CAMERA_DIAGNOSTIC_SNAPSHOT/)
  assert.match(kconfig, /config APP_CAMERA_DIAGNOSTIC_SNAPSHOT_DELAY_SECONDS/)
  assert.doesNotMatch(sdkconfig, /CONFIG_APP_CAMERA_DIAGNOSTIC_SNAPSHOT=y/)
})

