test('P4 camera sub-device BDD feature defines MIPI CSI SC2336 contract', () => {
  assert.ok(fs.existsSync(FEATURE_PATH), 'p4-camera.feature must exist')
  const feature = fs.readFileSync(FEATURE_PATH, 'utf8')
  assert.match(feature, /Feature: ESP32-P4 SC2336 camera subsystem/)
  assert.match(feature, /SC2336 1080P CMOS image sensor/)
  assert.match(feature, /SDA GPIO 7 and SCL GPIO 8/)
  assert.match(feature, /GPIO 26/)
  assert.match(feature, /MIPI CSI-2/)
  assert.match(feature, /Real on-device face detection and recognition metadata/)
  assert.match(feature, /rather than emitting a fixed face count/)
  assert.match(feature, /Physical owner enrollment and recognition/)
  assert.match(feature, /owner-confirmation button is physically pressed/)
  assert.match(feature, /Enrollment fails closed without valid physical confirmation/)
  assert.match(feature, /experimental owner-recognition result remains unavailable/)
  assert.match(feature, /exactly one valid face is visible to the P4 camera/)
  assert.match(feature, /confirmation request that outlives its 30 second window is also cleared/)
  assert.match(feature, /Temporary local diagnostic snapshot for hardware alignment/)
  assert.match(feature, /production image does not expose a camera preview or diagnostic snapshot/)
  assert.match(feature, /Structured face recognition metadata protocol/)
})

