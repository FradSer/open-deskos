test('P4 native USB exposes a UVC camera and a standard 16 kHz mono UAC microphone', () => {
  const feature = fs.readFileSync(FEATURE_PATH, 'utf8')
  const manifest = fs.readFileSync(COMPONENT_MANIFEST_PATH, 'utf8')
  const cmake = fs.readFileSync(CMAKE_PATH, 'utf8')
  const kconfig = fs.readFileSync(KCONFIG_PATH, 'utf8')
  const sdkconfig = fs.readFileSync(SDKCONFIG_DEFAULTS_PATH, 'utf8')
  const main = fs.readFileSync(CAMERA_MAIN_PATH, 'utf8')

  assert.match(feature, /USB Audio Class microphone/)
  assert.match(feature, /OSPTEK ESP32-P4C6 module baseboard V1\.3 schematic/)
  assert.match(feature, /ADC output into P4 GPIO 11/)
  assert.match(feature, /signed 16-bit mono PCM at 16 kHz/)
  assert.match(manifest, /espressif\/usb_device_uac:/)
  assert.match(manifest, /espressif\/esp_codec_dev:/)
  assert.match(cmake, /p4_usb_microphone\.c/)
  assert.match(kconfig, /config APP_USB_MICROPHONE/)
  assert.match(kconfig, /config APP_AUDIO_I2S_BCLK_PIN/)
  assert.match(kconfig, /config APP_AUDIO_I2S_WS_PIN/)
  assert.match(kconfig, /config APP_AUDIO_I2S_DIN_PIN/)
  assert.match(sdkconfig, /CONFIG_USB_DEVICE_UAC_AS_PART=y/)
  assert.match(sdkconfig, /CONFIG_UAC_MIC_CHANNEL_NUM=1/)
  assert.match(sdkconfig, /CONFIG_UAC_SAMPLE_RATE=16000/)
  assert.match(main, /p4_peripheral_i2c_init\(&peripheral_i2c\)/)
  assert.match(main, /p4_sc2336_init_hardware\(&pins, peripheral_i2c\)/)
  assert.match(main, /p4_usb_microphone_init\(peripheral_i2c\)/)
  assert.ok(fs.existsSync(AUDIO_HEADER_PATH), 'p4_usb_microphone.h must exist')
  assert.ok(fs.existsSync(AUDIO_SOURCE_PATH), 'p4_usb_microphone.c must exist')

  const audio = fs.readFileSync(AUDIO_SOURCE_PATH, 'utf8')
  assert.match(audio, /uac_device_init/)
  assert.match(audio, /\.skip_tinyusb_init = true/)
  assert.match(audio, /esp_codec_dev_read/)
  assert.match(audio, /\.sample_rate = 16000/)
  assert.match(audio, /\.channel = 1/)
  assert.match(audio, /\.bits_per_sample = 16/)
  assert.match(audio, /i2s_channel_enable/)
  assert.match(audio, /\.channel_mask = 0x01/)
  assert.match(audio, /audio I2S pins are not configured/)
  assert.match(audio, /Microphone self-test: samples=%u min=%d max=%d mean=%d ac_peak=%u ac_rms=%u clipped=%u/)
  assert.match(audio, /ac_peak >= 32 && ac_rms >= 8/)
  assert.match(audio, /clipped <= sample_count \/ 100/)
  assert.match(audio, /discard microphone startup samples/)
  assert.doesNotMatch(audio, /ESP_LOG[IE].*buffer/)
  assert.match(sdkconfig, /CONFIG_APP_AUDIO_I2S_MCLK_PIN=13/)
  assert.match(sdkconfig, /CONFIG_APP_AUDIO_I2S_BCLK_PIN=12/)
  assert.match(sdkconfig, /CONFIG_APP_AUDIO_I2S_WS_PIN=10/)
  assert.match(sdkconfig, /CONFIG_APP_AUDIO_I2S_DIN_PIN=11/)
})

test('CM5 P4 microphone acceptance validates live USB audio without storing speech', () => {
  assert.ok(fs.existsSync(MIC_ACCEPTANCE_PATH), 'p4-microphone-acceptance.sh must exist')
  const script = fs.readFileSync(MIC_ACCEPTANCE_PATH, 'utf8')
  assert.match(script, /lsusb -d "\$USB_ID"/)
  assert.match(script, /arecord -D "hw:\$CARD,\$DEVICE" -t raw -f S16_LE -r 16000 -c 1/)
  assert.match(script, /expected_bytes = int\(sys\.argv\[1\]\) \* 16000 \* 2/)
  assert.match(script, /python3 -c/)
  assert.match(script, /ac_rms/)
  assert.match(script, /clipped/)
  assert.doesNotMatch(script, /CDC/)
  assert.doesNotMatch(script, />\s*\/tmp\/.*\.(wav|raw)/)
})

