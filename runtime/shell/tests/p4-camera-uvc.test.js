test('P4 firmware contains no face, expression, enrollment, or metadata code', () => {
  for (const missing of [
    'p4_face_inference.cpp',
    'p4_face_inference.h',
    'p4_expression_policy.c',
    'p4_expression_policy.h',
    'p4_camera_protocol.c',
    'p4_camera_protocol.h',
  ]) {
    assert.ok(!fs.existsSync(path.join(CAMERA_ROOT, 'main', missing)), `${missing} must be deleted`)
  }
  const main = fs.readFileSync(CAMERA_MAIN_PATH, 'utf8')
  assert.doesNotMatch(main, /p4_face_inference/)
  assert.doesNotMatch(main, /p4_camera_protocol/)
  assert.doesNotMatch(main, /p4_expression/)
  assert.doesNotMatch(main, /OWNER_CONFIRM/)
  assert.doesNotMatch(main, /cdcacm/)
  assert.doesNotMatch(main, /DIAGNOSTIC_SNAPSHOT/)
  assert.match(main, /p4_uvc_stream_init/)
  assert.match(main, /p4_uvc_stream_start/)
  assert.match(main, /p4_usb_microphone_init\(peripheral_i2c\)/)
  assert.match(main, /p4_sc2336_init_hardware\(&pins, peripheral_i2c\)/)
})

