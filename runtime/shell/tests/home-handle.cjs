'use strict'
const { app, BrowserWindow, ipcMain, session } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { installHomePreviewFixtures } = require('./helpers/home-preview-fixtures')
const { createAppManagerEndpoint } = require('../src/app-manager-endpoint')
if (process.platform === 'darwin') app.dock.hide()
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'odk-home-handle-'))
const evidence = fs.mkdtempSync(path.join(os.tmpdir(), 'odk-home-handle-evidence-'))
app.setPath('userData', profile)
let win
const deadline = setTimeout(() => finish(1, Error('Home handle acceptance timed out')), 90000)
function finish(code, error) {
  clearTimeout(deadline)
  if (error) console.error(error)
  win?.destroy()
  try { fs.rmSync(profile, { recursive: true, force: true }) } catch {}
  app.exit(code)
}
app.whenReady().then(async () => {
  session.defaultSession.setPermissionRequestHandler((_win, _permission, done) => done(false))
  session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_request, done) => done({ cancel: true }))
  installHomePreviewFixtures(ipcMain)
  const endpoint = createAppManagerEndpoint()
  ipcMain.handle('odk-app-manager-intent', (_event, intent) => endpoint.dispatch(intent))
  win = new BrowserWindow({ show: false, width: 1280, height: 800, useContentSize: true,
    webPreferences: { preload: path.join(__dirname, '../src/preload.js'), sandbox: true, contextIsolation: true, backgroundThrottling: false, offscreen: true } })
  win.setContentSize(1280, 800)
  const js = expression => win.webContents.executeJavaScript(expression)
  await win.loadFile(path.join(__dirname, '../src/renderer/index.html'))
  await js('window.odkShellReady')
  await js(`window.until = async predicate => { const end=performance.now()+5000; while(!predicate()){if(performance.now()>end)throw Error('Handle condition timed out: '+predicate);await new Promise(r=>setTimeout(r,20))} }; void 0`)
  win.webContents.debugger.attach('1.3')
  await win.webContents.debugger.sendCommand('Emulation.setFocusEmulationEnabled', { enabled: true })
  await win.webContents.debugger.sendCommand('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 2 })
  const input = (method, params) => win.webContents.debugger.sendCommand(method, params)
  async function key(key, code = key) {
    const n = { Escape:27, ArrowUp:38, ArrowLeft:37, ArrowRight:39, Enter:13 }[key]
    await input('Input.dispatchKeyEvent', { type:'keyDown', key, code, windowsVirtualKeyCode:n })
    await input('Input.dispatchKeyEvent', { type:'keyUp', key, code, windowsVirtualKeyCode:n })
  }
  async function handlePoint() {
    return js(`(() => { const r=document.querySelector('#dots .dot.active').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2} })()`)
  }
  let timestamp = Date.now()/1000 - 30
  async function touch(type, points) { timestamp+=0.12; await input('Input.dispatchTouchEvent', { type, touchPoints:points, timestamp }) }
  async function swipe(dx, dy, cancel = false, origin = null) {
    const p=origin || await handlePoint()
    await touch('touchStart',[{...p,id:1}])
    for(const part of [0.25,0.5,0.75,1]) await touch('touchMove',[{x:p.x+dx*part,y:p.y+dy*part,id:1}])
    await touch(cancel?'touchCancel':'touchEnd',[])
  }
  const open = () => js(`(async()=>{document.querySelectorAll('.dot')[0].click();document.querySelector('[data-widget="odk.tile.futu"] .widget-launch').click();await until(()=>odkAppPlatform.active()?.sourceWidget==='odk.tile.futu'&&!document.getElementById('app-view').hidden);await document.fonts.ready})()`)
  const isOpen = () => js(`!document.getElementById('app-view').hidden`)
  const regressions = []
  function check(condition, message) { if (!condition) regressions.push(message) }
  // Inject a standard pad at the browser boundary. The Shell's real poller and
  // gamepad mapping must deliver B; a Remote event alone cannot prove this path.
  await js(`window.fixturePad={index:0,id:'Acceptance gamepad',connected:true,mapping:'standard',buttons:Array.from({length:17},()=>({pressed:false,value:0}))};Object.defineProperty(navigator,'getGamepads',{configurable:true,value:()=>[fixturePad]});window.dispatchEvent(new Event('gamepadconnected'))`)
  async function padB(pressed) {
    await js(`fixturePad.buttons[1]={pressed:${pressed},value:${pressed ? 1 : 0}};window.dispatchEvent(new Event('gamepadconnected'))`)
  }
  for (const theme of ['instrument','pixel','border-beam','liquid-glass']) {
    await js(`(async()=>{await odkTheme.set('${theme}');await document.fonts.ready;await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))})()`)
    const home=await js(`(() => {const visible=[...document.querySelectorAll('#dots .dot')].filter(n=>n.getClientRects().length);const n=visible[0],r=n?.getBoundingClientRect(),s=n&&getComputedStyle(n,'::before');return {count:visible.length,height:r?.height,width:r?.width,label:n?.getAttribute('aria-label'),marker:s&&[parseFloat(s.width),parseFloat(s.height)]}})()`)
    assert.equal(home.count,1,'Home must display one handle instead of a row of page marks')
    assert.ok(home.height>=44 && home.width>=100)
    assert.ok(home.marker[0]>=80 && home.marker[1]>=4 && home.marker[1]<=6,JSON.stringify(home))
    await input('Emulation.setEmulatedMedia',{features:[{name:'forced-colors',value:'active'}]})
    const forced=await js(`(()=>{const n=document.querySelector('.dot.active'),s=getComputedStyle(n,'::before');return {active:matchMedia('(forced-colors: active)').matches,marker:s.backgroundColor,text:getComputedStyle(n).color,adjust:s.forcedColorAdjust}})()`)
    assert.equal(forced.active,true)
    assert.equal(forced.marker,forced.text,'The forced-colors handle must use the contrasting control foreground')
    assert.equal(forced.adjust,'none')
    await js('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))')
    fs.writeFileSync(path.join(evidence,`${theme}-forced-home.png`),(await win.webContents.capturePage()).toPNG())
    await input('Emulation.setEmulatedMedia',{features:[]})
    await swipe(-100,0)
    assert.equal(await js(`document.querySelectorAll('.dot')[1].getAttribute('aria-current')`),'page')
    await js(`document.querySelector('.dot.active').focus()`)
    await key('ArrowLeft')
    assert.equal(await js(`document.activeElement===document.querySelector('.dot.active')`),true,'Page changes must retain focus on the handle')
    await open()
    assert.equal(await js(`document.getElementById('app-back').getClientRects().length`),0)
    const chrome = await js(`(()=>{const title=document.getElementById('app-title'),s=getComputedStyle(title),r=title.getBoundingClientRect();return {header:document.querySelector('#app-view > .app-header').getBoundingClientRect().height,titleHidden:s.position==='absolute'&&r.width<=1&&r.height<=1,name:title.textContent,label:document.getElementById('app-view').getAttribute('aria-labelledby')}})()`)
    check(chrome.header===0 && chrome.titleHidden, theme+': no visible Shell title or empty header')
    check(chrome.name==='Futu holdings' && chrome.label==='app-title', theme+': retained accessible App name')
    // The SDK owns a clipped shape and exposes its effective radius in --lg-radius.
    // Its host borderRadius is zero while the visible shape remains rounded.
    const frame=await js(`(() => {const source=getComputedStyle(document.querySelector('[data-widget="odk.tile.futu"]'));const card=document.getElementById('app-view'),s=getComputedStyle(card),inner=getComputedStyle(document.querySelector('#app-runtime > *')),r=card.getBoundingClientRect(),h=document.querySelector('.dot.active').getBoundingClientRect();return {source:[source.borderTopWidth,source.borderTopColor,source.clipPath!=='none'&&source.getPropertyValue('--lg-radius').trim()?parseFloat(source.getPropertyValue('--lg-radius'))+'px':source.borderTopLeftRadius],app:[s.borderTopWidth,s.borderTopColor,s.borderTopLeftRadius],outline:s.outlineStyle,innerBorder:inner.borderTopWidth,inside:r.left>=document.getElementById('desk-content').getBoundingClientRect().left&&r.right<=innerWidth&&r.bottom<=h.top,handleHit:document.querySelector('.dot.active').contains(document.elementFromPoint(h.x+h.width/2,h.y+h.height/2))}})()`)
    assert.deepEqual(frame.app,frame.source,'App card frame must match its source Widget')
    assert.equal(frame.outline,'none')
    assert.equal(frame.innerBorder,'0px')
    assert.equal(frame.inside,true)
    assert.equal(frame.handleHit,true)
    await input('Emulation.setEmulatedMedia',{features:[{name:'forced-colors',value:'active'}]})
    const forcedOrigin=await handlePoint()
    await touch('touchStart',[{...forcedOrigin,id:1}])
    await touch('touchMove',[{x:forcedOrigin.x,y:forcedOrigin.y-24,id:1}])
    const forcedDrag=await js(`(()=>{const n=document.querySelector('.dot.active');return {dragging:document.getElementById('dots').hasAttribute('data-dragging'),marker:getComputedStyle(n,'::before').backgroundColor,text:getComputedStyle(n).color}})()`)
    assert.equal(forcedDrag.dragging,true)
    assert.equal(forcedDrag.marker,forcedDrag.text,'Active App return must retain its forced-colors marker')
    await touch('touchCancel',[])
    await input('Emulation.setEmulatedMedia',{features:[]})
    await js(`document.querySelector('#app-runtime').setAttribute('tabindex','-1');document.querySelector('#app-runtime').focus()`)
    await key('Escape')
    await js(`document.getElementById('app-back').click()`)
    assert.equal(await isOpen(),true,'Escape and hidden Back cannot bypass handle return')
    await swipe(0,-16)
    assert.equal(await isOpen(),true,'Short movement must not return')
    await swipe(65,0)
    assert.equal(await isOpen(),true,'Horizontal App handle movement must not return')
    await swipe(0,-96,true)
    assert.equal(await isOpen(),true,'Cancelled gestures must not return')
    const body=await js(`(()=>{const r=document.querySelector('.app-body').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height*.7}})()`)
    await swipe(0,-96,false,body)
    assert.equal(await isOpen(),true,'Content scrolling cannot dismiss the App')
    await swipe(0,-96)
    await js(`until(()=>document.getElementById('app-view').hidden)`)
    assert.equal(await js(`document.activeElement===document.querySelector('[data-widget="odk.tile.futu"] .widget-launch')`),true)
    await open()
    await js(`document.querySelector('.dot.active').focus()`)
    await key('ArrowUp')
    await js(`until(()=>document.getElementById('app-view').hidden)`)
    await open()
    await padB(true)
    await js('new Promise(r=>setTimeout(r,100))')
    check(!await isOpen(),theme+': gamepad B returns from the App')
    if (await isOpen()) await js('odkAppPlatform.closeApp()')
    else check(await js(`document.activeElement===document.querySelector('[data-widget="odk.tile.futu"] .widget-launch')`),theme+': B restores source focus')
    await open()
    await js('new Promise(r=>setTimeout(r,100))')
    check(await isOpen(),theme+': held B does not close the next App')
    await padB(false)
    win.webContents.send('odk-personal-bot-status',{state:'recording',activated:true,transcript:'',message:''})
    await js('until(()=>odkPersonalBotStatus.visible())')
    await padB(true)
    await js('until(()=>!odkPersonalBotStatus.visible())')
    check(await isOpen(),theme+': B dismisses the Personal Bot overlay before the App')
    await padB(false)
    win.webContents.send('odk-personal-bot-status',{state:'idle',transcript:'',message:''})
    await js('odkAppPlatform.closeApp()')
    console.log(`PASS ${theme}: one home handle, swipe-only pointer return, keyboard equivalent, gamepad B, retained focus and matching card frame`)
    await js('document.activeElement.blur(); new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))')
    fs.writeFileSync(path.join(evidence,`${theme}-home.png`),(await win.webContents.capturePage()).toPNG())
    await open()
    await js('document.activeElement.blur(); new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))')
    fs.writeFileSync(path.join(evidence,`${theme}-app.png`),(await win.webContents.capturePage()).toPNG())
    await js(`odkAppPlatform.closeApp()`)
  }
  await js(`delete navigator.getGamepads;delete window.fixturePad;window.dispatchEvent(new Event('gamepaddisconnected'))`)
  for (const [width,height] of [[1920,1280],[960,640],[480,854],[320,480]]) {
    win.setContentSize(width,height)
    await js('window.dispatchEvent(new Event("resize"))')
    await js(`until(()=>window.__odkGrid.width===${width}&&window.__odkGrid.height===${height})`)
    await open()
    await js('document.getElementById("page-center").scrollIntoView({block:"end"})')
    const bounds=await js(`(()=>{const r=document.getElementById('app-view').getBoundingClientRect(),h=document.querySelector('.dot.active').getBoundingClientRect();return {inside:r.left>=0&&r.right<=innerWidth&&r.height>100,handle:h.y>=0&&h.bottom<=innerHeight+1&&h.height===44}})()`)
    assert.equal(bounds.inside,true);assert.equal(bounds.handle,true)
    await swipe(0,-96)
    await js('until(()=>document.getElementById("app-view").hidden)')
    console.log(`PASS ${width}x${height}: reachable bottom handle and contained App card`)
  }
  assert.deepEqual(regressions, [], 'App chrome and gamepad regressions')
  console.log('HOME_HANDLE_PASS '+evidence)
  finish(0)
}).catch(error=>finish(1,error))
