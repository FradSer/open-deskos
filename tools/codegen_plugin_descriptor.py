#!/usr/bin/env python3
"""
tools/codegen_plugin_descriptor.py
Generates static C plugin descriptors (.rodata) from manifest.json for ESP-IDF firmware.
"""

import json
import os
import re
import sys

KIND_MAP = {
    "device-driver": "ODK_KIND_DEVICE_DRIVER",
    "transport": "ODK_KIND_TRANSPORT",
    "processor": "ODK_KIND_PROCESSOR",
    "service": "ODK_KIND_SERVICE",
    "surface": "ODK_KIND_SURFACE",
    "protocol": "ODK_KIND_PROTOCOL",
}


def c_string(value: str) -> str:
    # Fixed-width octal escapes keep control bytes separate from following text.
    escapes = {byte: f"\\{byte:03o}" for byte in range(32)}
    escapes.update({127: "\\177", ord('"'): '\\"', ord("\\"): "\\\\", ord("?"): "\\?"})
    return '"' + value.translate(escapes) + '"'


def generate_c_descriptors(manifest_paths: list[str], out_header: str, out_source: str) -> None:
    plugins = []
    for path in manifest_paths:
        with open(path, "r", encoding="utf-8") as f:
            plugin = json.load(f)
            lifecycle = plugin.get("lifecycle")
            if lifecycle is not None and (not isinstance(lifecycle, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", lifecycle)):
                raise ValueError("lifecycle must be a native C symbol")
            public = {field: plugin[field] for field in ("schemaVersion", "id", "name", "version", "host", "kind") if field in plugin}
            public.setdefault("schemaVersion", 1)
            public.setdefault("name", plugin["id"])
            public.setdefault("version", "1.0.0")
            public.setdefault("kind", "service")
            for field in ("provides", "requires"):
                public[field] = [{key: value for key, value in port.items() if key in ("interface", "optional")}
                                 for port in plugin.get(field, [])]
            public["permissions"] = plugin.get("permissions", [])
            plugin["public_manifest_json"] = json.dumps(public, ensure_ascii=True, separators=(",", ":"))
            if len(plugin["public_manifest_json"].encode("utf-8")) > 16384:
                raise ValueError("public plugin manifest exceeds report limit")
            plugins.append(plugin)

    # Generate Header
    with open(out_header, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by tools/codegen_plugin_descriptor.py - DO NOT EDIT */\n")
        f.write("#pragma once\n\n")
        f.write('#include "odk_plugin_host.h"\n\n')
        f.write(f"extern const odk_plugin_descriptor_t g_odk_plugins[{len(plugins)}];\n")
        f.write(f"extern const size_t g_odk_plugins_count;\n")

    # Generate Source
    with open(out_source, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by tools/codegen_plugin_descriptor.py - DO NOT EDIT */\n")
        f.write(f'#include "{os.path.basename(out_header)}"\n\n')

        for lifecycle in dict.fromkeys(plugin.get("lifecycle") for plugin in plugins):
            if lifecycle is not None:
                f.write(f"extern const odk_plugin_lifecycle_t {lifecycle};\n")
        f.write("\n")

        # Manifest IDs are data; input positions give private C symbols unique names.
        for ident, p in enumerate(plugins):
            provides = p.get("provides", [])
            requires = p.get("requires", [])

            if provides:
                f.write(f"static const odk_port_desc_t s_provides_{ident}[] = {{\n")
                for port in provides:
                    uri = port.get("interface", "")
                    f.write(f'    {{ {c_string(uri)}, false }},\n')
                f.write("};\n\n")

            if requires:
                f.write(f"static const odk_port_desc_t s_requires_{ident}[] = {{\n")
                for port in requires:
                    uri = port.get("interface", "")
                    opt = "true" if port.get("optional") else "false"
                    f.write(f'    {{ {c_string(uri)}, {opt} }},\n')
                f.write("};\n\n")

        f.write(f"const odk_plugin_descriptor_t g_odk_plugins[{len(plugins)}] = {{\n")
        for ident, p in enumerate(plugins):
            kind = KIND_MAP.get(p.get("kind"), "ODK_KIND_SERVICE")
            provides = p.get("provides", [])
            requires = p.get("requires", [])

            prov_ptr = f"s_provides_{ident}" if provides else "NULL"
            req_ptr = f"s_requires_{ident}" if requires else "NULL"

            f.write("    {\n")
            f.write(f'        .id = {c_string(p["id"])},\n')
            f.write(f'        .name = {c_string(p.get("name", p["id"]))},\n')
            f.write(f"        .version = 1,\n")
            f.write(f"        .kind = {kind},\n")
            lifecycle = f"&{p['lifecycle']}" if p.get("lifecycle") else "NULL"
            f.write(f"        .lifecycle = {lifecycle},\n")
            f.write(f"        .provides_count = {len(provides)},\n")
            f.write(f"        .provides = {prov_ptr},\n")
            f.write(f"        .requires_count = {len(requires)},\n")
            f.write(f"        .requires = {req_ptr},\n")
            host = c_string(p["host"]) if p.get("host") is not None else "NULL"
            f.write(f"        .host = {host},\n")
            f.write(f"        .manifest_json = {c_string(p['public_manifest_json'])},\n")
            f.write("    },\n")
        f.write("};\n\n")
        f.write(f"const size_t g_odk_plugins_count = {len(plugins)};\n")


if __name__ == "__main__":
    if len(sys.argv) < 4:
        print("Usage: codegen_plugin_descriptor.py <out_header> <out_source> <manifest1.json> [manifest2.json...]")
        sys.exit(1)
    generate_c_descriptors(sys.argv[3:], sys.argv[1], sys.argv[2])
